/**
 * Reserved origin-banner strip per banner width, read from the generated table.
 *
 * Kept apart from `constants.ts` and `originBannerLayout.ts` so `scripts/generate-banner-size.ts`
 * never imports its own output: a missing or merge-conflicted table can always be regenerated.
 */
import {bannerWidthKey, PIXELS_PER_MM} from './constants.js';
import {ORIGIN_BANNER_STRIP_PPM, ORIGIN_BANNER_STRIP_PX} from './originBannerStrip.generated.js';
import {sheetSafeMarginsMm} from './sheetGeometry.js';

/** Width (mm) the origin banner spans on a sheet this size: between its left and right safe margins. */
export function originBannerWidthMm(paperWMm: number, paperHMm: number): number {
    const m = sheetSafeMarginsMm(paperWMm, paperHMm);
    return paperWMm - m.left - m.right;
}

/**
 * Origin-banner strip (mm, from the safe top margin through the gap below the banner) on a sheet this
 * size. Tiling (`tiling.ts`, and so `feasibilityRules.ts`) and the renderer (`svgAssemblyCore.ts`) both
 * use it, so the sheet count shown in the UI is the sheet count printed. Each value is the exact
 * rendered banner height (`originBannerLayout.ts`), generated by `npm run generate:banner`; rerun that
 * whenever banner text, type, layout constants or safe margins change.
 */
export function originBannerReserveMm(paperWMm: number, paperHMm: number): number {
    const bannerWMm = originBannerWidthMm(paperWMm, paperHMm);
    const px = ORIGIN_BANNER_STRIP_PX[bannerWidthKey(bannerWMm)];
    if (px === undefined || ORIGIN_BANNER_STRIP_PPM !== PIXELS_PER_MM) {
        throw new Error(
            `No generated origin-banner height for a ${bannerWMm} mm banner (${paperWMm} × ${paperHMm} mm sheet) at ${PIXELS_PER_MM} px/mm; run \`npm run generate:banner\`.`,
        );
    }
    return px / PIXELS_PER_MM;
}
