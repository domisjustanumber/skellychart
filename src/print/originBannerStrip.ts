/**
 * Reserved origin-banner strip per sheet width, read from the generated table.
 *
 * Kept apart from `constants.ts` and `originBannerLayout.ts` so `scripts/generate-banner-size.ts`
 * never imports its own output: a missing or merge-conflicted table can always be regenerated.
 */
import {PIXELS_PER_MM, sheetWidthKey} from './constants.js';
import {ORIGIN_BANNER_STRIP_PPM, ORIGIN_BANNER_STRIP_PX} from './originBannerStrip.generated.js';

/**
 * Origin-banner strip (mm, from the top of the printable area through the gap below the banner) on a
 * sheet of this width. Tiling (`tiling.ts`, and so `feasibilityRules.ts`) and the renderer
 * (`svgAssemblyCore.ts`) both use it, so the sheet count shown in the UI is the sheet count printed.
 * Each value is the exact rendered banner height (`originBannerLayout.ts`), generated by
 * `npm run generate:banner`; rerun that whenever banner text, type or layout constants change.
 */
export function originBannerReserveMm(paperWMm: number): number {
    const px = ORIGIN_BANNER_STRIP_PX[sheetWidthKey(paperWMm)];
    if (px === undefined || ORIGIN_BANNER_STRIP_PPM !== PIXELS_PER_MM) {
        throw new Error(
            `No generated origin-banner height for a ${paperWMm} mm sheet at ${PIXELS_PER_MM} px/mm; run \`npm run generate:banner\`.`,
        );
    }
    return px / PIXELS_PER_MM;
}
